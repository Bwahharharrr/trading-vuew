// Math functions for ScriptStd

export default {
    /** Absolute value
     * @param {number} x - Input
     * @return {number} - Absolute value
     */
    abs(x) {
        return Math.abs(x)
    },

    /** Arccosine function
     * @param {number} x - Input
     * @return {number} - Arccosine of x
     */
    acos(x) {
        return Math.acos(x)
    },

    /** Arcsine function
     * @param {number} x - Input
     * @return {number} - Arcsine of x
     */
    asin(x) {
        return Math.asin(x)
    },

    /** Arctangent function
     * @param {number} x - Input
     * @return {number} - Arctangent of x
     */
    atan(x) {
        return Math.atan(x)
    },

    /** Shortcut for Math.ceil()
     * @param {number} x The variable
     * @return {number}
     */
    ceil(x) {
        return Math.ceil(x)
    },

    /** Cosine function
     * @param {number} x - Input
     * @return {number} - Cosine of x
     */
    cos(x) {
        return Math.cos(x)
    },

    /** Shortcut for Math.exp()
     * @param {number} x The variable
     * @return {number}
     */
    exp(x) {
        return Math.exp(x)
    },

    /** Shortcut for Math.floor()
     * @param {number} x The variable
     * @return {number}
     */
    floor(x) {
        return Math.floor(x)
    },

    /** Shortcut for Math.log()
     * @param {number} x The variable
     * @return {number}
     */
    log(x) {
        return Math.log(x)
    },

    /** Shortcut for Math.log10()
     * @param {number} x The variable
     * @return {number}
     */
    log10(x) {
        return Math.log10(x)
    },

    /** Shortcut for Math.pow()
     * @param {number} x The variable
     * @return {number}
     */
    pow(x, y) {
        return Math.pow(x, y)
    },

    /** Shortcut for Math.round()
     * @param {number} x The variable
     * @return {number}
     */
    round(x) {
        return Math.round(x)
    },

    /** Shortcut for Math.sign()
     * @param {number} x The variable
     * @return {number}
     */
    sign(x) {
        return Math.sign(x)
    },

    /** Sine function
     * @param {number} x The variable
     * @return {number}
     */
    sin(x) {
        return Math.sin(x)
    },

    /** Shortcut for Math.sqrt()
     * @param {number} x The variable
     * @return {number}
     */
    sqrt(x) {
        return Math.sqrt(x)
    },

    /** Tangent function
     * @param {number} x The variable
     * @return {number}
     */
    tan(x) {
        return Math.tan(x)
    }
}
